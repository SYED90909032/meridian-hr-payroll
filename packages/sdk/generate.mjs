import fs from 'node:fs';
const spec = JSON.parse(fs.readFileSync(new URL('./openapi.json', import.meta.url), 'utf8'));
const paths = Object.keys(spec.paths ?? {}).sort();
const methods = [];
for (const path of paths) for (const method of Object.keys(spec.paths[path]).sort()) methods.push([method.toUpperCase(), path]);
const lines = [`// Generated by generate.mjs from openapi.json. Do not edit.`, `export const openApiPaths = ${JSON.stringify(paths)} as const;`, `export type OpenApiPath = typeof openApiPaths[number];`, `export const openApiOperations = ${JSON.stringify(methods)} as const;`, `export type OpenApiOperation = typeof openApiOperations[number];`, ''];
fs.writeFileSync(new URL('./src/generated.ts', import.meta.url), lines.join('\n'));
